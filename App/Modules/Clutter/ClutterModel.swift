import AppKit
import ReviveKit
import QuickLookThumbnailing
import SwiftUI

@MainActor @Observable
final class ClutterModel {
    enum Phase: Equatable { case idle, scanning, ready, removing }
    enum Section: Hashable { case duplicates, similar, large, screenshots }

    private(set) var phase: Phase = .idle
    var section: Section?
    private(set) var progress = ScanProgress(currentPath: "", bytesFound: 0)
    private(set) var result = ClutterResult()
    var selection: Set<String> = []
    private(set) var lastReport: RemovalReport?

    @ObservationIgnored unowned let app: AppModel
    @ObservationIgnored private var task: Task<Void, Never>?

    init(app: AppModel) {
        self.app = app
    }

    /// Opens a section, scanning first if needed (used by Shortcuts).
    func open(_ section: Section) {
        self.section = section
        if phase == .idle { scan() }
    }

    func scan() {
        task?.cancel()
        phase = .scanning
        let home = app.safetyGuard.home
        let onProgress: @Sendable (ScanProgress) -> Void = { [weak self] progress in
            Task { @MainActor in self?.progress = progress }
        }
        task = Task {
            let result = await Task.detached(priority: .userInitiated) {
                await ClutterScanner(home: home).scan(progress: onProgress)
            }.value
            guard !Task.isCancelled else { return }
            self.result = result
            // Every copy but the one to keep starts checked; big files are the user's call.
            selection = Set((result.duplicates + result.similarPhotos).flatMap { $0.files.dropFirst().map(\.id) })
            phase = .ready
        }
    }

    func stop() {
        task?.cancel()
        phase = .idle
    }

    func toggle(_ file: ClutterFile) {
        if selection.contains(file.id) { selection.remove(file.id) } else { selection.insert(file.id) }
    }

    func files(in section: Section) -> [ClutterFile] {
        switch section {
        case .duplicates: result.duplicates.flatMap(\.files)
        case .similar: result.similarPhotos.flatMap(\.files)
        case .large: result.largeOldFiles
        case .screenshots: result.screenshots
        }
    }

    func selectedSize(in section: Section) -> Int64 {
        files(in: section).filter { selection.contains($0.id) }.reduce(0) { $0 + $1.size }
    }

    func selectedCount(in section: Section) -> Int {
        Set(files(in: section).map(\.id)).intersection(selection).count
    }

    func removeSelected(in section: Section) {
        var seen = Set<String>()
        let chosen = files(in: section).filter { selection.contains($0.id) && seen.insert($0.id).inserted }
        guard !chosen.isEmpty else { return }
        phase = .removing
        Task {
            let report = await WorkspaceRemover.recycle(chosen.map(\.asCleanupItem), policy: .userInitiated,
                                                        safetyGuard: app.safetyGuard, dryRun: app.dryRun)
            lastReport = report
            app.record(report, module: .myClutter)
            if !report.wasSimulated {
                let failed = Set(report.failures.map(\.path))
                let removed = Set(chosen.map(\.id)).filter { !failed.contains($0) }
                prune(removed)
            }
            phase = .ready
        }
    }

    private func prune(_ removed: Set<String>) {
        func clean(_ groups: [ClutterGroup]) -> [ClutterGroup] {
            groups.map { ClutterGroup(id: $0.id, files: $0.files.filter { !removed.contains($0.id) }) }.filter { $0.files.count > 1 }
        }
        result.duplicates = clean(result.duplicates)
        result.similarPhotos = clean(result.similarPhotos)
        result.largeOldFiles.removeAll { removed.contains($0.id) }
        result.screenshots.removeAll { removed.contains($0.id) }
        selection.subtract(removed)
    }
}

/// Thumbnail of a file, generated by Quick Look.
struct Thumbnail: View {
    let url: URL
    var size: CGFloat = 120
    @State private var image: NSImage?

    var body: some View {
        ZStack {
            RoundedRectangle(cornerRadius: 10).fill(.white.opacity(0.08))
            if let image {
                Image(nsImage: image).resizable().scaledToFill()
            } else {
                Image(nsImage: NSWorkspace.shared.icon(forFile: url.path(percentEncoded: false))).resizable().scaledToFit().padding(size * 0.2)
            }
        }
        .frame(width: size, height: size)
        .clipShape(RoundedRectangle(cornerRadius: 10))
        .task(id: url) {
            let request = QLThumbnailGenerator.Request(fileAt: url, size: CGSize(width: size, height: size),
                                                       scale: NSScreen.main?.backingScaleFactor ?? 2, representationTypes: .thumbnail)
            if let thumbnail = try? await QLThumbnailGenerator.shared.generateBestRepresentation(for: request) {
                image = thumbnail.nsImage
            }
        }
    }
}
